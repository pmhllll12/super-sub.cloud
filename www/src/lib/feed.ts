/**
 * 홈에서 아래로 내리면 나오는 **영상 모음**.
 *
 * 🔴 이건 분석 리포트가 아니라 **사람들이 올린 장면**이다. 잘 골라 놓은 것을
 * 훑어보는 자리라, 여기서는 수치도 판정도 안 보여준다 — 누가 언제 무엇을
 * 올렸는지만 적는다(부록 D.5 의 "카드에 수치를 그리지 않는다"와 같은 결).
 *
 * ⚠️ 전부 mock 이다. 지금 쓰는 파일은 코치 카드가 쓰는 것과 **같은 클립**이다
 * (저장소에 있는 영상이 그것뿐이라서다) — 계약에 영상 조회가 생기면
 * (5장 ASM-003, 객체 저장소 미정) 이 상수를 지우고 응답을 흘려 넣으면 된다.
 */
export type FeedClip = {
  id: string
  /** 큰 글자로 얹히는 제목. 짧을수록 좋다. */
  title: string
  /** 올린 사람. */
  by: string
  /**
   * 올린 날(YYYY-MM-DD).
   *
   * ⚠️ **화면에는 안 내보낸다**(사용자 요청). 언제 올렸는지가 보이면 오래된 것이
   * 낡아 보이는데, 여기는 잘 찍힌 장면을 훑는 자리지 새 소식을 보는 자리가
   * 아니다. 값은 남겨 둔다 — 나중에 정렬(최신순)에 쓸 것이다.
   */
  at: string
  /** 한 줄 설명 — 무엇을 보는 장면인지. */
  what: string
  src: string
  /**
   * 화면 비율(`가로 / 세로`).
   *
   * 🔴 **틀에 맞춰 자르지 않는다**(사용자 요청) — 세로로 찍은 것은 세로 그대로
   * 세운다. 폰으로 찍은 장면이 대부분일 자리라, 가로 틀에 우겨넣으면 사람 머리와
   * 발이 잘린다.
   * 🔴 값을 **미리 적어 두는** 것이 중요하다. 영상을 읽어서 알아내면 그때 칸의
   * 크기가 바뀌어 화면이 한 번 덜컥한다. API 가 붙으면 서버가 같이 준다.
   */
  aspect: string
}

