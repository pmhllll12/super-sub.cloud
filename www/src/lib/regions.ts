/**
 * 적은 글자로 후보를 고른다. **이미 고른 것은 빼고** 준다 — 두 번 넣을 수 없다.
 *
 * 🔴 빈 글자에는 아무것도 안 준다. 목록 전체를 늘어놓으면 60줄이 화면을 덮는다.
 * 🔴 띄어쓰기를 지우고 견준다 — 「서울강남」으로 적어도 걸린다.
 */
export function searchRegions(query: string, chosen: string[] = [], limit = 6): string[] {
  const q = query.replace(/\s+/g, '')
  if (!q) return []
  return REGIONS.filter(
    (r) => !chosen.includes(r) && r.replace(/\s+/g, '').includes(q),
  ).slice(0, limit)
}
