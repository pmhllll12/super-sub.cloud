/**
 * 카드 뒤에 깔리는 **자국**.
 *
 * 🔴 **2026-09-10 에 그림을 통째로 갈았다**(사용자 요청). 전에는 절차적 SVG
 * 열 가지(사선 · 빗살 · 호 …)였는데, 유화 · 수채 · 튄 자국 같은 **질감**은
 * 깨끗한 SVG 로 흉내 낼 수가 없다 — 그래서 그림을 **마스크**로 쓴다.
 *
 * 🔴 **색을 박은 그림이 아니라 마스크다.** `public/marks/*.png` 는 알파만
 * 담고 있고(LA 모드), 칠하는 것은 `currentColor` 다 — 그래야 「자국 색」이
 * 그대로 먹는다. 색이 구워진 그림이면 사용자가 고른 색이 죽는다.
 *
 * 🔴 크기 · 좌우 · 위아래는 `.ss-card-mark` 이 이미 받는다(`--ss-card-mark-*`).
 * 여기서는 **무엇을 그릴지만** 정한다.
 */

/**
 * 고를 수 있는 자국들.
 *
 * 🔴 첫 자리가 **기본**이다 — 사람 뒤에 원래 깔려 있던 붓칠
 * (`PlayerCardBrush`, 슬러그로 모양이 정해지는 그것)이다.
 * ⚠️ 한때 이 자리를 '없음' 으로 두었다가 되돌렸다: 편집을 여는 순간 붓칠이
 * 사라져, 고치기도 전에 카드가 달라져 버렸다.
 *
 * 🔴 **14~18 은 2026-09-18 에 더한 것**이다(사용자 요청). 손으로 그린 그림이
 * 아니라 `scripts/marks.html` 을 `scripts/bake-marks.py` 가 구워 낸 것이라 —
 * **PNG 를 직접 고치면 다음에 구울 때 조용히 덮인다.**
 * ⚠️ 그중 **글리치 스펙트럼 · 파티클 플럭스는 원본이 색으로 읽히는 것**
 * (색 번짐 · 검은 바탕의 반짝임)이라 **구조만** 남겼다(사용자 판단).
 * 마스크는 알파만 쓰므로 색을 넣을 자리가 없고, 색을 살리려면 「자국 색」이
 * 안 먹는 갈래를 따로 내야 한다.
 *
 * ⚠️ 처음엔 아홉을 더했다가 같은 날 **넷을 뺐다**(홀로그램 레이어 · 모래 폭풍 ·
 * 유동 금속 · 거친 숯 번짐 — 사용자 판단). 그 넷은 **배포된 적이 없어서**
 * 자리를 비우지 않고 통째로 지웠다. 아래 `HIDDEN_MARKS` 와 처리가 갈리는
 * 이유가 그것이다.
 */
