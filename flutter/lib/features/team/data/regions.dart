/// 저장할 수 있는 값인가 — 앞뒤 공백은 턴다.
bool isRegion(String value) => kRegions.contains(value.trim());

/// 적은 글로 후보를 좁힌다. 빈 글이면 **전부** 준다(처음 열었을 때 목록이
/// 비어 있으면 무엇을 고르는 칸인지 안 읽힌다).
List<String> searchRegions(String query, {int limit = 30}) {
  final q = query.trim();
  if (q.isEmpty) return kRegions.take(limit).toList();
  return [
    for (final r in kRegions)
      if (r.contains(q)) r,
  ].take(limit).toList();
}
