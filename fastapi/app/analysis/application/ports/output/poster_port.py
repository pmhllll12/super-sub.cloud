from abc import ABC, abstractmethod


class PosterPort(ABC):
    """영상에서 **한 장면을 떠서 JPEG** 로 만든다.

    🔴 **포트로 둔 까닭은 시험이다.** 실제 구현은 `ffmpeg` 프로세스를 띄우고
    바깥 망으로 나가므로, 계약 시험이 그걸 그대로 돌 수는 없다. 스텁으로
    갈아 끼워 "권한·캐시·404" 만 재도록 한다.
    """

    @abstractmethod
    def capture(self, media_url: str) -> bytes | None:
        """[media_url] 의 한 장면을 JPEG 바이트로. **못 뜨면 None.**

        🔴 **`media_url` 은 사전 서명된 GET 주소다** — 서버가 파일을 내려받아
        두지 않고 주소를 그대로 넘긴다. 그래서 **새 S3 권한이 필요 없다**
        (읽기는 이미 재생 주소를 만들 때 쓰던 그 권한이다).

        🔴 **맨 처음 프레임을 뜨지 않는다.** 시작 몇 프레임은 검거나 페이드인인
        경우가 많아서, 앞에서 조금 들어간 지점을 쓴다.

        🔴 **None 은 정상이다** — 형식을 못 읽거나 너무 짧은 영상이 있다.
        부르는 쪽은 그때 404 로 답하고, 화면은 자리표시를 그린다.
        """
